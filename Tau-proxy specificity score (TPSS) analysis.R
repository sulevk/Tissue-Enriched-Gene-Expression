# Tau-proxy specificity score (TPSS) analysis
#
# Purpose and methodological distinction:
#   This script calculates a Tau-inspired proxy specificity score (TPSS) from
#   existing significant one-versus-all DESeq2 result files. TPSS is NOT the
#   original tissue-specificity index (Tau) described by Yanai et al. (2005).
#   The original Tau index is calculated from a gene's expression profile
#   across tissues. Here, the input is instead a proxy matrix reconstructed
#   from significant tissue-versus-remainder log2 fold changes.
#
# Input files:
#   resSig*TissueLabel*FDR005.csv files generated by the existing DESeq2
#   workflow. Each file is expected to contain hgnc_symbol, log2FoldChange,
#   baseMean, and padj columns. This script does not rerun Salmon, tximeta,
#   or DESeq2.
#
# Proxy-matrix construction (retained from the original analysis):
#   proxy[gene, tissue] = 2^log2FoldChange when the gene appears in that
#                         tissue's significant resSig file
#                       = 1 otherwise.
#   Thus, entries for genes absent from a significant-result file are assigned
#   the neutral proxy value 1; they are not independently measured expression
#   values and should not be interpreted as proof of equal expression.
#
# TPSS is calculated using the Tau-form expression:
#   TPSS = sum_i(1 - x_i / max(x)) / (n_tissues - 1)
#   The formula is Tau-inspired, but its input matrix is a DESeq2-derived
#   proxy, so TPSS is not numerically or conceptually interchangeable with
#   the original Yanai Tau index. Interpret it as a proxy measure of the
#   tissue concentration of enrichment/depletion signals in this framework.
#
# The score calculation, threshold (0.85), comparisons, statistical tests,
# and plotting approach are retained from the original script. Output names
# use TPSS terminology to avoid implying that the original Yanai index was
# calculated.

install.packages("ggplot2")

getwd()

setwd("~/Documents/R_projects/your_analysis_folder")

length(list.files(
  pattern = "^resSig.*FDR005\\.csv$"
))

files <- list.files(pattern = '^resSig.*FDR005\\.csv$')
if (length(files) == 0) {
  stop('No matching resSig*FDR005.csv files found in the working directory. ',
       'Set the working directory to the folder containing the existing DESeq2 result files.')
}
if (length(files) < 2) {
  stop('At least two tissue result files are required to calculate TPSS.')
}

extract_label <- function(f) sub('^resSig(.*)FDR005\\.csv$', '\\1', f)
tissue_labels <- sort(vapply(files, extract_label, character(1)))
files <- files[order(vapply(files, extract_label, character(1)))]

# --- Load and clean each tissue's significant-gene table -------------------
read_tissue <- function(f) {
  d <- read.csv(f, stringsAsFactors = FALSE, check.names = FALSE)
  required_cols <- c('hgnc_symbol', 'log2FoldChange', 'baseMean', 'padj')
  missing_cols <- setdiff(required_cols, names(d))
  if (length(missing_cols)) {
    stop('File ', f, ' is missing required column(s): ',
         paste(missing_cols, collapse = ', '))
  }
  d <- d[!is.na(d$hgnc_symbol) & nzchar(d$hgnc_symbol) & is.finite(d$log2FoldChange), ]
  # Collapse duplicate symbols (multiple Ensembl IDs per HGNC symbol): keep
  # the row with the highest baseMean, matching the convention used
  # elsewhere in this project (make_top6_dotplot.R).
  if (any(duplicated(d$hgnc_symbol))) {
    d <- d[order(d$hgnc_symbol, -d$baseMean), ]
    d <- d[!duplicated(d$hgnc_symbol), ]
  }
  d[, c('hgnc_symbol', 'log2FoldChange', 'baseMean', 'padj')]
}

tissue_data <- setNames(lapply(files, read_tissue), tissue_labels)

all_genes <- sort(unique(unlist(lapply(tissue_data, `[[`, 'hgnc_symbol'))))
n_tissue <- length(tissue_labels)

# --- Build the proxy relative-expression matrix -----------------------------
proxy <- matrix(1, nrow = length(all_genes), ncol = n_tissue,
                dimnames = list(all_genes, tissue_labels))

for (tis in tissue_labels) {
  d <- tissue_data[[tis]]
  proxy[d$hgnc_symbol, tis] <- 2^d$log2FoldChange
}

# --- Compute Tau-proxy specificity score (TPSS) -------------------------------
tpss_of <- function(x) {
  xmax <- max(x)
  if (!is.finite(xmax) || xmax <= 0) return(NA_real_)
  sum(1 - x / xmax) / (n_tissue - 1)
}
tpss_vec <- apply(proxy, 1, tpss_of)

top_tissue_idx <- max.col(proxy, ties.method = 'first')
top_tissue <- tissue_labels[top_tissue_idx]
top_value <- proxy[cbind(seq_len(nrow(proxy)), top_tissue_idx)]

n_tissues_up <- rowSums(proxy > 1)
n_tissues_down <- rowSums(proxy < 1)

tpss_df <- data.frame(
  hgnc_symbol = all_genes,
  TPSS = tpss_vec,
  top_tissue = top_tissue,
  top_tissue_fold_change = top_value,
  n_tissues_up = n_tissues_up,
  n_tissues_down = n_tissues_down,
  stringsAsFactors = FALSE
)
tpss_df <- tpss_df[order(-tpss_df$TPSS), ]
write.csv(tpss_df, 'tau_proxy_specificity_scores.csv', row.names = FALSE)
cat('Created tau_proxy_specificity_scores.csv with', nrow(tpss_df), 'genes.\n')

# --- Compare TPSS with DE-based tissue enrichment ---------------------------
# DE-enriched set per tissue = genes with log2FoldChange > 0 in that tissue's
# resSig file (i.e. significantly UP in that tissue vs. the rest of the body).
# Retained analysis threshold; this is a working TPSS threshold, not a
# universally established cutoff for the original Yanai Tau index.
TPSS_THRESHOLD <- 0.85

summary_rows <- list()
for (tis in tissue_labels) {
  d <- tissue_data[[tis]]
  de_enriched <- unique(d$hgnc_symbol[d$log2FoldChange > 0])
  
  tpss_specific <- tpss_df$hgnc_symbol[tpss_df$TPSS >= TPSS_THRESHOLD & tpss_df$top_tissue == tis]
  
  overlap <- intersect(de_enriched, tpss_specific)
  union_n <- length(union(de_enriched, tpss_specific))
  
  summary_rows[[tis]] <- data.frame(
    tissue = tis,
    n_DE_enriched = length(de_enriched),
    n_tpss_specific = length(tpss_specific),
    n_overlap = length(overlap),
    pct_DE_enriched_confirmed_by_TPSS = round(100 * length(overlap) / max(length(de_enriched), 1), 1),
    jaccard = round(length(overlap) / max(union_n, 1), 3),
    stringsAsFactors = FALSE
  )
}
comparison_df <- do.call(rbind, summary_rows)
comparison_df <- comparison_df[order(-comparison_df$pct_DE_enriched_confirmed_by_TPSS), ]
write.csv(comparison_df, 'tpss_vs_DE_comparison_summary.csv', row.names = FALSE)
cat('Created tpss_vs_DE_comparison_summary.csv (', nrow(comparison_df), 'tissues ).\n')

# --- Check the specific "top 6" DE genes reported per tissue ----------------
top6_file <- 'top6_hgnc_by_tissue.csv'
if (file.exists(top6_file)) {
  top6 <- read.csv(top6_file, stringsAsFactors = FALSE, row.names = 1, check.names = FALSE)
  hgnc_cols <- grep('^hgnc_symbol_[1-6]$', names(top6), value = TRUE)
  
  rows <- list()
  idx <- 1
  for (tis in rownames(top6)) {
    for (col in hgnc_cols) {
      gene <- top6[tis, col]
      if (is.na(gene) || gene == '') next
      tpss_row <- tpss_df[tpss_df$hgnc_symbol == gene, ]
      rows[[idx]] <- data.frame(
        tissue = tis,
        gene_rank = col,
        hgnc_symbol = gene,
        TPSS = if (nrow(tpss_row) == 1) tpss_row$TPSS else NA_real_,
        tpss_top_tissue = if (nrow(tpss_row) == 1) tpss_row$top_tissue else NA_character_,
        tpss_top_tissue_agrees_with_DE_tissue = if (nrow(tpss_row) == 1) identical(tpss_row$top_tissue, tis) else NA,
        stringsAsFactors = FALSE
      )
      idx <- idx + 1
    }
  }
  top6_tpss <- do.call(rbind, rows)
  write.csv(top6_tpss, 'top6_DE_genes_tpss_comparison.csv', row.names = FALSE)
  cat('Created top6_DE_genes_tpss_comparison.csv:',
      sum(top6_tpss$tpss_top_tissue_agrees_with_DE_tissue, na.rm = TRUE), 'of', nrow(top6_tpss),
      'top DE genes have their highest TPSS-based specificity in the same tissue.\n')
}

cat('\n--- Overall summary ---\n')
cat('Genes with TPSS available:', sum(!is.na(tpss_df$TPSS)), '\n')
cat('Genes with TPSS >=', TPSS_THRESHOLD, ':', sum(tpss_df$TPSS >= TPSS_THRESHOLD, na.rm = TRUE), '\n')
cat('Mean TPSS across all genes:', round(mean(tpss_df$TPSS, na.rm = TRUE), 3), '\n')
cat('Median % of DE-enriched genes per tissue confirmed by TPSS (>=', TPSS_THRESHOLD, '):',
    round(median(comparison_df$pct_DE_enriched_confirmed_by_TPSS), 1), '%\n')

# --- Wilcoxon rank-sum test: TPSS in DE-enriched vs. non-enriched genes ------
# H1: genes flagged as tissue-enriched by DE have higher TPSS than genes that
# were never called enriched (one-sided, alternative = 'greater').
enriched_any <- unique(unlist(lapply(tissue_data, function(d) d$hgnc_symbol[d$log2FoldChange > 0])))
tpss_df$enriched_any <- tpss_df$hgnc_symbol %in% enriched_any

wilcox_rows <- list()

w_any <- wilcox.test(tpss_df$TPSS[tpss_df$enriched_any], tpss_df$TPSS[!tpss_df$enriched_any], alternative = 'greater')
wilcox_rows[['ANY_TISSUE']] <- data.frame(
  tissue = 'ANY_TISSUE',
  n_enriched = sum(tpss_df$enriched_any),
  n_not_enriched = sum(!tpss_df$enriched_any),
  median_TPSS_enriched = median(tpss_df$TPSS[tpss_df$enriched_any], na.rm = TRUE),
  median_TPSS_not_enriched = median(tpss_df$TPSS[!tpss_df$enriched_any], na.rm = TRUE),
  W_statistic = unname(w_any$statistic),
  p_value = w_any$p.value,
  stringsAsFactors = FALSE
)

# Per-tissue: genes enriched in this specific tissue vs. all other genes.
# Note: the "not enriched here" group also contains genes that are highly
# specific to OTHER tissues (high TPSS), so per-tissue results are confounded
# relative to the ANY_TISSUE test, which uses a clean never-enriched-anywhere
# background.
for (tis in tissue_labels) {
  de_enriched <- unique(tissue_data[[tis]]$hgnc_symbol[tissue_data[[tis]]$log2FoldChange > 0])
  is_enriched_here <- tpss_df$hgnc_symbol %in% de_enriched
  if (length(unique(is_enriched_here)) < 2) next
  w <- wilcox.test(tpss_df$TPSS[is_enriched_here], tpss_df$TPSS[!is_enriched_here], alternative = 'greater')
  wilcox_rows[[tis]] <- data.frame(
    tissue = tis,
    n_enriched = sum(is_enriched_here),
    n_not_enriched = sum(!is_enriched_here),
    median_TPSS_enriched = median(tpss_df$TPSS[is_enriched_here], na.rm = TRUE),
    median_TPSS_not_enriched = median(tpss_df$TPSS[!is_enriched_here], na.rm = TRUE),
    W_statistic = unname(w$statistic),
    p_value = w$p.value,
    stringsAsFactors = FALSE
  )
}

wilcox_df <- do.call(rbind, wilcox_rows)
wilcox_df$p_value_BH_adj <- p.adjust(wilcox_df$p_value, method = 'BH')
wilcox_df <- wilcox_df[order(wilcox_df$p_value_BH_adj), ]
write.csv(wilcox_df, 'tpss_wilcoxon_enrichment_test.csv', row.names = FALSE)

cat('\n--- Wilcoxon rank-sum test: TPSS (enriched vs. non-enriched) ---\n')
cat('ANY_TISSUE: median TPSS enriched =', round(wilcox_rows[['ANY_TISSUE']]$median_TPSS_enriched, 3),
    'vs. non-enriched =', round(wilcox_rows[['ANY_TISSUE']]$median_TPSS_not_enriched, 3),
    ', p =', format.pval(w_any$p.value, digits = 3), '\n')
cat('Created tpss_wilcoxon_enrichment_test.csv (', nrow(wilcox_df), 'tests: ANY_TISSUE + per-tissue ).\n')
cat('Tissues with significant BH-adjusted p < 0.05:', sum(wilcox_df$p_value_BH_adj < 0.05), 'of', nrow(wilcox_df), '\n')

# --- Spearman correlation: TPSS vs. positive log2FoldChange (enriched genes) -
# top_tissue_fold_change = 2^log2FoldChange in the gene's argmax tissue, so
# log2() of it recovers the log2FoldChange that drove the enrichment call.
enriched_df <- tpss_df[tpss_df$enriched_any, ]
enriched_df$log2FC_top_tissue <- log2(enriched_df$top_tissue_fold_change)
enriched_df <- enriched_df[enriched_df$log2FC_top_tissue > 0, ]

spearman <- cor.test(enriched_df$TPSS, enriched_df$log2FC_top_tissue, method = 'spearman', exact = FALSE)

spearman_df <- data.frame(
  n_genes = nrow(enriched_df),
  spearman_rho = unname(spearman$estimate),
  S_statistic = unname(spearman$statistic),
  p_value = spearman$p.value,
  stringsAsFactors = FALSE
)
write.csv(spearman_df, 'tpss_vs_log2FC_spearman.csv', row.names = FALSE)

cat('\n--- Spearman correlation: TPSS vs. positive log2FoldChange (enriched genes) ---\n')
cat('n =', spearman_df$n_genes, ', rho =', round(spearman_df$spearman_rho, 3),
    ', p =', format.pval(spearman_df$p_value, digits = 3), '\n')
cat('Created tpss_vs_log2FC_spearman.csv.\n')

